export function projectsTranslator(locale: Locale, numberingSystem?: NumberingSystem) {
  return createTranslator({
    locale: localeWithNumberingSystem(locale, numberingSystem),
    messages: messages[locale],
  });
}

export type ProjectsTranslator = ReturnType<typeof projectsTranslator>;
